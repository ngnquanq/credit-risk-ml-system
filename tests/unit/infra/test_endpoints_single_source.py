"""Service addresses are defined once, in platform/config/endpoints/endpoints.env.

Manifests read them from the shared-endpoints ConfigMap. This test fails when a manifest writes one
of those addresses out again. A file listed in PENDING still does, for the reason given; remove it
from the list when it is converted, so the list only ever shrinks.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ENV_FILE = ROOT / "platform/config/endpoints/endpoints.env"
SCANNED = ["services", "platform/core", "platform/data", "platform/environments", "portals/deploy", "scripts/local"]
# platform/ml mixes our files with vendored charts, so only our own files are listed.
EXTRA_FILES = ["platform/ml/k8s/model-serving/watcher-deployment.yaml", "platform/ml/k8s/knative/serving-config.yaml"]
SUFFIXES = {".yaml", ".yml", ".template", ".sh"}

# The component itself, and the broker's own statement of where it listens, are sources.
SOURCE = {"platform/data/k8s/message-broker/01-kafka.yaml"}

# Not converted yet: file -> why.
PENDING: dict[str, str] = {
    "services/feature-store/feast_repo/feature_store.yaml": (
        "Scoring loads this file inside the Bento with no environment for it. Feast expands ${VAR} but leaves "
        "an unset name as written, which would break local runs. The deployed pods use feast-store-config instead."
    ),
    "services/model-lifecycle/pipeline/training_pipeline.yaml": (
        "Generated by compile_pipeline.py from the defaults in pipeline.py; they are Kubeflow run parameters."
    ),
}


def _endpoints() -> dict[str, str]:
    out = {}
    for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            key, _, value = line.partition("=")
            out[key.strip()] = value.strip()
    return out


def _hits() -> dict[str, set[str]]:
    values = _endpoints()
    hits: dict[str, set[str]] = {}
    paths = [p for base in SCANNED for p in (ROOT / base).rglob("*")] + [ROOT / f for f in EXTRA_FILES]
    for path in paths:
        if path.suffix not in SUFFIXES or not path.is_file():
            continue
        if {"charts", "kubeflow", ".generated"} & set(path.parts):
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        for key, value in values.items():
            if value in text:
                hits.setdefault(str(path.relative_to(ROOT)), set()).add(key)
    return hits


def test_no_manifest_writes_a_shared_address_out():
    unexpected = {f: sorted(k) for f, k in _hits().items() if f not in SOURCE and f not in PENDING}
    assert not unexpected, (
        f"{unexpected} write a shared address out. Read it from the shared-endpoints ConfigMap "
        "(platform/config/endpoints) instead."
    )


def test_pending_list_has_no_converted_files():
    converted = set(PENDING) - set(_hits())
    assert not converted, f"Remove {sorted(converted)} from PENDING: they no longer hard-code an address."


def test_every_key_is_a_non_empty_public_value():
    for key, value in _endpoints().items():
        assert value, key
        assert not any(w in key.upper() for w in ("PASSWORD", "SECRET", "TOKEN", "KEY")), (
            f"{key} looks like a secret; secrets never go in endpoints.env"
        )
